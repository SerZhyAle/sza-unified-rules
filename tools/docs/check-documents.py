"""Validate independent documentation corpora. Codes: 0 pass, 1 violations, 2 unavailable.

--register inventories sources; --render regenerates only declared documentation maps.
Normal validation never writes a registry, derivative or document.
"""

import argparse
import json
import re
import subprocess
import sys
from pathlib import Path
from urllib.parse import unquote, urlsplit


def prose(text):
    lines = []
    fence = None
    for line in text.splitlines():
        match = re.match(r"^\s*(`{3,}|~{3,})", line)
        if match:
            marker = match[1][0]
            if fence is None:
                fence = marker
            elif fence == marker:
                fence = None
            lines.append("")
        else:
            lines.append(line if fence is None else "")
    return "\n".join(lines)


def anchors(text):
    found, counts = set(), {}
    for line in prose(text).splitlines():
        heading = re.match(r"^ {0,3}#{1,6}\s+(.+?)(?:\s+#+)?$", line)
        if heading:
            title = re.sub(r"<[^>]+>", "", heading[1]).lower()
            title = re.sub(r"[^\w\- ]", "", title, flags=re.UNICODE).replace(" ", "-")
            number = counts.get(title, 0)
            counts[title] = number + 1
            found.add(title + (f"-{number}" if number else ""))
    found.update(re.findall(r'''(?:id|name)=["']([^"']+)["']''', prose(text)))
    return found


def links(text):
    text = prose(text)
    # Commands and literal syntax examples are not navigable links.
    text = re.sub(r"(`+).*?\1", "", text)
    definitions = dict(re.findall(r"(?m)^\s*\[([^]]+)\]:\s*<?([^\s>]+)>?", text))
    for match in re.finditer(r"(!?)\[[^]\n]*\]\(\s*(<[^>]+>|[^\s)]+)(?:\s+[^)]*)?\)", text):
        yield match[2].strip("<>"), bool(match[1])
    for match in re.finditer(r"(!?)\[([^]\n]+)\]\[([^]\n]*)\]", text):
        key = match[3] or match[2]
        yield definitions.get(key, f"missing-reference:{key}"), bool(match[1])
    for match in re.finditer(r"(?m)^\s*\[[^]]+\]:\s*<?([^\s>]+)>?", text):
        yield match[1], False
    for match in re.finditer(r'''<(img|script|iframe|link|a)\b[^>]*?\b(?:src|href)=["']([^"']+)["']''', text, re.I):
        yield match[2], match[1].lower() != "a"
    for match in re.finditer(r"<(https?://[^>]+)>", text):
        yield match[1], False
    for match in re.finditer(r'''(?:url\(\s*["']?|@import\s+["'])(https?://[^\s)'";]+)''', text, re.I):
        yield match[1], True


def inventory(root, config):
    files = set()
    for item in config["roots"]:
        path = root / item
        if not path.exists():
            raise ValueError(f"Missing maintained root: {item}")
        candidates = path.rglob("*") if path.is_dir() else [path]
        files.update(p.relative_to(root).as_posix() for p in candidates
                     if p.is_file() and p.suffix.lower() in (".md", ".rst", ".html"))
    for ignore in config.get("ignore", []):
        if not ignore.get("reason"):
            raise ValueError("Ignore entry needs a reason")
        files = {f for f in files if not Path(f).match(ignore["pattern"])}
    return files


def render_map(records):
    lines = ["# Documentation map", "", "Generated by `python tools/docs/check-documents.py --render`. Do not edit.", "",
             "| Document | Topic | Area | Role |", "| --- | --- | --- | --- |"]
    for record in sorted(records, key=lambda r: r["path"]):
        target = "../" + record["path"]
        lines.append(f"| [{record['path']}]({target}) | {record['topic'].replace('|', '/')} | {record['area']} | {record['role']} |")
    return "\n".join(lines) + "\n"


def check_corpus(root, config_path, register=False, render=False):
    config = json.loads(config_path.read_text(encoding="utf-8-sig"))
    registry = root / config["registry"]
    files = inventory(root, config)
    local = config["visibility"] == "local"
    if register:
        existing = {r["path"]: r for r in read_records(registry)} if registry.exists() else {}
        records = []
        for name in sorted(files):
            record = existing.get(name, {})
            lines = (root / name).read_text(encoding="utf-8-sig").splitlines()
            topic = lines[0].lstrip("# ") if lines else Path(name).stem
            records.append({"path": name, "topic": record.get("topic", topic),
                            "area": record.get("area", name.split("/")[0] if "/" in name else "repository"),
                            "update_triggers": record.get("update_triggers", ["Changes to the documented interface or workflow"]),
                            "role": "render" if name == config["map"] else "source"})
        registry.parent.mkdir(parents=True, exist_ok=True)
        registry.write_text("".join(json.dumps(r, ensure_ascii=False) + "\n" for r in records), encoding="utf-8")
    records = read_records(registry)
    errors, declared = [], set()
    tracked = subprocess.run(["git", "-C", str(root), "ls-files", "-z"], capture_output=True, check=True).stdout.decode().split("\0")
    ignored = subprocess.run(["git", "-C", str(root), "ls-files", "--others", "--ignored", "--exclude-standard", "-z"], capture_output=True, check=True).stdout.decode().split("\0")
    ignored = set(ignored)
    # Ignore policy applies to tracked legacy files too, including files pending removal from the index.
    candidates = set(tracked) | files | {r["path"] for r in records} | {config["registry"]}
    ignored.update(subprocess.run(
        ["git", "-C", str(root), "check-ignore", "--no-index", "-z", "--stdin"],
        input="\0".join(sorted(candidates - {""})).encode() + b"\0", capture_output=True
    ).stdout.decode().split("\0"))
    for record in records:
        name = record["path"]
        if not all(record.get(k) for k in ("topic", "area", "update_triggers", "role")) or record["role"] not in ("source", "render"):
            errors.append(f"{name}: incomplete registry record")
        if name in declared:
            errors.append(f"{name}: duplicate authoritative record")
        declared.add(name)
        if name not in files:
            errors.append(f"{name}: registry entry outside maintained corpus or missing")
        if not local and name in ignored:
            errors.append(f"{name}: published registry exposes an ignored document")
        if local and name not in ignored:
            errors.append(f"{name}: local document must remain ignored")
        if record["role"] == "render" and name != config["map"]:
            errors.append(f"{name}: no registered generator")
    errors.extend(f"{name}: missing registry entry" for name in sorted(files - declared))
    expected_map = render_map(records)
    map_path = root / config["map"]
    if render:
        map_path.write_text(expected_map, encoding="utf-8")
    if not map_path.exists() or map_path.read_text(encoding="utf-8") != expected_map:
        errors.append(f"{config['map']}: generated derivative drift")
    if local and config["registry"] not in ignored:
        errors.append("Local registry must remain ignored")
    for name in sorted(files):
        path = root / name
        text = path.read_text(encoding="utf-8-sig")
        readable = re.sub(r"(`+).*?\1", "", prose(text))
        if re.search(r"[\u2013\u2014\u2015\u2026]|(?<!\.)\.{3}(?!\.)", readable):
            errors.append(f"{name}: house style requires plain hyphens and two periods in prose")
        for target, asset in links(text):
            parsed = urlsplit(target)
            if parsed.scheme or target.startswith("//"):
                if parsed.scheme != "https" and not (parsed.scheme == "mailto" and not asset):
                    errors.append(f"{name}: unsafe external reference: {target}")
                elif asset:
                    errors.append(f"{name}: remote embedded asset is unavailable offline: {target}")
                continue
            destination = (root / unquote(parsed.path).lstrip("/")) if target.startswith("/") else (path.parent / unquote(parsed.path))
            if not parsed.path:
                destination = path
            destination = destination.resolve()
            if not destination.is_relative_to(root):
                errors.append(f"{name}: link escapes repository: {target}")
                continue
            if not destination.exists():
                errors.append(f"{name}: missing target: {target}")
                continue
            relative = destination.relative_to(root).as_posix()
            if not local and relative in ignored:
                errors.append(f"{name}: published link exposes ignored document: {target}")
            if asset and ((local and relative not in files and not relative.startswith(tuple(r + "/" for r in config["roots"]))) or
                          (not local and relative not in tracked)):
                errors.append(f"{name}: asset outside local corpus or not tracked: {target}")
            if parsed.fragment:
                heading_source = destination / "README.md" if destination.is_dir() else destination
                if heading_source.suffix.lower() in (".md", ".html", ".rst") and heading_source.exists():
                    if unquote(parsed.fragment) not in anchors(heading_source.read_text(encoding="utf-8-sig")):
                        errors.append(f"{name}: missing anchor: {target}")
    return errors, len(files)


def read_records(path):
    return [json.loads(line) for line in path.read_text(encoding="utf-8-sig").splitlines() if line.strip()]


def main():
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument("--root", type=Path, default=Path(__file__).resolve().parents[2])
    parser.add_argument("--config", type=Path, action="append")
    parser.add_argument("--register", action="store_true")
    parser.add_argument("--render", action="store_true")
    parser.add_argument("--init-local", action="store_true")
    args = parser.parse_args()
    root = args.root.resolve()
    try:
        local_config = root / "dev/document-corpus.json"
        if args.init_local and not local_config.exists():
            local_config.parent.mkdir(parents=True, exist_ok=True)
            roots = ["dev"] + (["PLAN"] if (root / "PLAN").exists() else [])
            local_config.write_text(json.dumps({
                "visibility": "local", "registry": "dev/DOCUMENT_REGISTRY.jsonl", "map": "dev/DOCS_MAP.md",
                "roots": roots, "ignore": [{"pattern": "PLAN/DONE/*.md", "reason": "Frozen completed ticket records; no archive rewrite."}]
            }, indent=2) + "\n", encoding="utf-8")
            (root / "dev/DOCS_MAP.md").touch(exist_ok=True)
        configs = args.config or [Path("docs/document-corpus.json")]
        if args.config is None and local_config.exists():
            configs.append(Path("dev/document-corpus.json"))
        errors, count = [], 0
        for config in configs:
            findings, inspected = check_corpus(root, root / config, args.register, args.render)
            errors.extend(findings)
            count += inspected
        for error in errors:
            print(error)
        print(f"documents: {'FAIL' if errors else 'PASS'} (corpora={len(configs)} files={count} errors={len(errors)})")
        return 1 if errors else 0
    except (OSError, ValueError, KeyError, subprocess.CalledProcessError) as error:
        print(error)
        print("documents: COULD NOT VERIFY")
        return 2


if __name__ == "__main__":
    sys.exit(main())
